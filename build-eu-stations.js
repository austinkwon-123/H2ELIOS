const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const SRC = "C:/Users/user/Downloads/Hydrogen refuelling stations May2026 (1).xlsx";
const SOURCE_URL = "https://ipcei.observatory.clean-hydrogen.europa.eu/tools-reports/datasets";

// Europe/UK/EFTA bounding box, generous enough to catch outliers without
// silently accepting a badly-parsed geolocation string.
function inEuropeBounds(lng, lat) {
  return lng >= -25 && lng <= 45 && lat >= 34 && lat <= 72;
}

function dispenserSummary(bar700, bar350, bar350hd) {
  const parts = [];
  if (bar700) parts.push(`${bar700}× 700 bar`);
  if (bar350) parts.push(`${bar350}× 350 bar`);
  if (bar350hd) parts.push(`${bar350hd}× 350 bar HD`);
  return parts.length ? parts.join(" · ") : "Dispenser count not disclosed";
}

const wb = XLSX.readFile(SRC);
const ws = wb.Sheets["HRS"];
const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: null, raw: true });

const feats = [];
let skipped = 0;

for (let i = 1; i < rows.length; i++) {
  const r = rows[i];
  if (!r || !r[1]) continue;

  const geolocation = r[9];
  if (!geolocation || typeof geolocation !== "string") { skipped++; continue; }
  const parts = geolocation.split(",").map((s) => parseFloat(s.trim()));
  if (parts.length !== 2 || parts.some((n) => Number.isNaN(n))) { skipped++; continue; }
  const [lng, lat] = parts;
  if (!inEuropeBounds(lng, lat)) { skipped++; continue; }

  const name = String(r[1]).trim();
  const city = r[7] ? String(r[7]).trim() : "";
  const country = r[8] ? String(r[8]).trim() : "";
  const operator = r[2] || r[4] || r[3] || null;

  feats.push({
    type: "Feature",
    geometry: { type: "Point", coordinates: [parseFloat(lng.toFixed(5)), parseFloat(lat.toFixed(5))] },
    properties: {
      name: city ? `${name}${name === city ? "" : ` (${city})`}` : name,
      category: "end_use",
      subtype: "Fueling Station",
      color: "gray_blue",
      region: "europe",
      scale: 1,
      statusClass: "operating",
      status: "Operating",
      capacity: dispenserSummary(r[10], r[11], r[12]),
      operator: operator ? String(operator).trim() : "—",
      country,
      source: SOURCE_URL,
      updated: "May 2026",
      tier: "eu-stations"
    }
  });
}

const out = { type: "FeatureCollection", features: feats };
const meta = {
  count: feats.length,
  skipped,
  label: "IPCEI Clean Hydrogen Observatory — Hydrogen Refuelling Stations (May 2026)",
  source: SOURCE_URL
};

const outputFilePath = path.join(__dirname, 'js/eu-stations-data.js');
const fileContent = `// Generated by build-eu-stations.js from the IPCEI Clean Hydrogen Observatory
// dataset (${SOURCE_URL}). Do not hand-edit.
window.EU_STATIONS_META = ${JSON.stringify(meta, null, 2)};
window.EU_STATIONS_DATA = ${JSON.stringify(out)};
`;

fs.writeFileSync(outputFilePath, fileContent, 'utf8');
console.log(`Generated js/eu-stations-data.js with ${feats.length} features (${skipped} skipped).`);
