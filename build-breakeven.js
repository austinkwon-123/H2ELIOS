const XLSX = require('xlsx');
const fs = require('fs');
const path = require('path');

const DL = "C:/Users/user/Downloads/";
const YEARS = [2022, 2023, 2024, 2025];
const SOURCE_URL = "https://ipcei.observatory.clean-hydrogen.europa.eu/tools-reports/datasets";

// Leading blank-row count before the header varies by year/sheet (2022's
// Maritime sheet has 6 blank rows, 2025's has none) - slicing off a fixed
// row count is unsafe. Filter by the known header label in col 1 instead.
function readSheet(wb, name, headerLabel) {
  const ws = wb.Sheets[name];
  if (!ws) return [];
  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, defval: null, raw: true });
  return rows.filter((r) => r && r[1] && String(r[1]).trim() !== headerLabel);
}

const refining = {};   // country -> { 2022: v, 2023: v, ... }
const hdtrucks = {};   // country -> { 2022: { delivered, production }, ... }
const maritime = {};   // application -> { 2022: v, ... }

YEARS.forEach((year) => {
  const file = `${DL}Break-even prices of renewable hydrogen ${year}.xlsx`;
  const wb = XLSX.readFile(file);

  readSheet(wb, "Refining", "Country").forEach((r) => {
    const country = String(r[1]).trim();
    refining[country] = refining[country] || {};
    refining[country][year] = typeof r[2] === "number" ? r[2] : null;
  });

  readSheet(wb, "HDtrucks", "Country").forEach((r) => {
    const country = String(r[1]).trim();
    hdtrucks[country] = hdtrucks[country] || {};
    hdtrucks[country][year] = {
      delivered: typeof r[2] === "number" ? r[2] : null,
      production: typeof r[3] === "number" ? r[3] : null
    };
  });

  readSheet(wb, "Maritime", "Maritime application").forEach((r) => {
    const app = String(r[1]).trim();
    maritime[app] = maritime[app] || {};
    maritime[app][year] = typeof r[2] === "number" ? r[2] : null;
  });
});

function toSeries(obj, valueOf) {
  return Object.keys(obj).sort().map((key) => ({
    key,
    values: YEARS.map((y) => {
      const v = obj[key][y];
      return v == null ? null : (valueOf ? valueOf(v) : Math.round(v * 1000) / 1000);
    })
  }));
}

const out = {
  years: YEARS,
  sectors: {
    refining: {
      label: "Oil Refining",
      unit: "EUR/kg",
      series: toSeries(refining)
    },
    hdtrucks: {
      label: "Heavy-Duty Trucks",
      unit: "EUR/kg",
      series: toSeries(hdtrucks, (v) => Math.round(v.delivered * 1000) / 1000),
      seriesAtProduction: toSeries(hdtrucks, (v) => Math.round(v.production * 1000) / 1000)
    },
    maritime: {
      label: "Maritime",
      unit: "EUR/kg",
      series: toSeries(maritime)
    }
  }
};

const meta = {
  label: "IPCEI Clean Hydrogen Observatory — Break-Even Prices of Renewable Hydrogen (2022-2025)",
  source: SOURCE_URL,
  years: YEARS
};

const outputFilePath = path.join(__dirname, 'js/breakeven-data.js');
const fileContent = `// Generated by build-breakeven.js from the IPCEI Clean Hydrogen Observatory
// break-even price datasets (${SOURCE_URL}). Do not hand-edit.
window.BREAKEVEN_META = ${JSON.stringify(meta, null, 2)};
window.BREAKEVEN_DATA = ${JSON.stringify(out, null, 2)};
`;

fs.writeFileSync(outputFilePath, fileContent, 'utf8');
console.log(`Generated js/breakeven-data.js — refining: ${out.sectors.refining.series.length} countries, hdtrucks: ${out.sectors.hdtrucks.series.length} countries, maritime: ${out.sectors.maritime.series.length} applications.`);
